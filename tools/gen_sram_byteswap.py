#!/usr/bin/env python3
"""Generate port/generated/byteswap/sram_layout.c: where the 2- and 4-byte
scalars of struct Sram (include/structs/save_file.h) are, as runs of same-width
scalars. A big-endian port keeps the save in host order in memory and swaps
those scalars when mzm.sav is read or written, so the file stays the GBA's
byte for byte (port/port_sram_swap.c, docs/wiiu-big-endian-plan.md, part F).

struct Sram has the GBA's layout on every 32-bit host (port_gba_struct_layout.h),
so the layout devkitARM's gcc gives it (read back from DWARF, as
tools/gen_rom_type_map.py does for the ROM) is the host's too.

    python3 tools/gen_sram_byteswap.py [--check]

--check compares with the checked-in file instead of writing it (exit 1 if it
differs). Needs devkitARM (DEVKITARM or C:/devkitPro/devkitARM,
/opt/devkitpro/devkitARM). Run it again after a change to the save structs.
"""
import argparse
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_rom_type_map as romtypes  # noqa: E402

OUT = os.path.join(romtypes.ROOT, "port", "generated", "byteswap", "sram_layout.c")
PROBE = '#include "types.h"\n#include "structs/save_file.h"\nstruct Sram probe;\n'
SRAM_STRUCT_SIZE = 0x7F90


def sram_ops():
    gcc = romtypes.devkitarm_bin("gcc")
    readelf = romtypes.devkitarm_bin("readelf")
    with tempfile.TemporaryDirectory() as workdir:
        source = os.path.join(workdir, "sram_probe.c")
        with open(source, "w", encoding="utf-8") as f:
            f.write(PROBE)
        dwarf, _ = romtypes.compile_file(source, "REGION_EU", workdir, gcc, readelf)
    dies = romtypes.parse_dwarf(dwarf)
    types = romtypes.Types(dies)
    found = romtypes.variables(dies)
    if "probe" not in found:
        sys.exit("struct Sram not found in the probe's DWARF")
    size, _, ops = types.layout(found["probe"])
    for warning in sorted(types.warnings):
        print("warning:", warning, file=sys.stderr)
    if size != SRAM_STRUCT_SIZE:
        sys.exit("struct Sram is 0x%x bytes, not the GBA's 0x%x" % (size, SRAM_STRUCT_SIZE))
    return ops


def runs_of(ops):
    """[(offset, width, count)]: consecutive scalars of one width, back to back."""
    runs = []
    for offset, width in ops:
        if runs and runs[-1][1] == width and runs[-1][0] + runs[-1][1] * runs[-1][2] == offset:
            runs[-1][2] += 1
        else:
            runs.append([offset, width, 1])
    return runs


def render(runs):
    lines = ["/* Generated by tools/gen_sram_byteswap.py. Do not edit.",
             " * The 2- and 4-byte scalars of struct Sram, as runs, for keeping mzm.sav",
             " * in the GBA's byte order on a big-endian host (port/port_sram_swap.c). */",
             '#include "port_sram_swap.h"', "",
             "const PortSramRun gPortSramRuns[] = {"]
    for offset, width, count in runs:
        lines.append("    { 0x%04x, %d, %d }," % (offset, width, count))
    lines += ["};", "",
              "const unsigned gPortSramRunCount = sizeof(gPortSramRuns) / sizeof(gPortSramRuns[0]);", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render(runs_of(sram_ops()))
    if args.check:
        try:
            current = open(OUT, encoding="utf-8").read()
        except OSError:
            current = None
        if current != text:
            sys.exit("%s is out of date: run tools/gen_sram_byteswap.py" % OUT)
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s" % OUT)


if __name__ == "__main__":
    main()
