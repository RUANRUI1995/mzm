#!/usr/bin/env python3
"""Bakes the 12x12 Chinese glyphs the 3DS bottom screen needs.

The bottom screen draws its own text (platform/3ds/source/port_bottom_ui_3ds.c)
with a 5x7 Latin font built into that file. Chinese needs real glyphs, so they
are cut out of a pixel font here and written as data
(port_bottom_ui_font_zh.c): only the characters the Chinese catalogue
(port_bottom_ui_zh.c) actually uses, which keeps it to a few kilobytes instead
of a whole font.

The font is fusion-pixel-font (https://github.com/TakWolf/fusion-pixel-font),
SIL OFL 1.1. Download the 12px monospaced release and pass either the .bdf in
the bdf zip (exact bitmaps) or the .ttf in the ms.bitmap.ttf zip (its outlines
are the same pixels, drawn at 12px):

  python tools/ui-font-zh/gen.py fusion-pixel-12px-monospaced-zh_hans.bdf
  python tools/ui-font-zh/gen.py fusion-pixel-12px-monospaced-ms.bitmap.ttf

Run it again whenever the catalogue gains a character it did not have; it fails
when the font has no glyph for one, which is the point (a missing glyph draws
nothing at all).
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CATALOGUE = os.path.join(ROOT, 'platform', '3ds', 'source', 'port_bottom_ui_zh.c')
OUT = os.path.join(ROOT, 'platform', '3ds', 'source', 'port_bottom_ui_font_zh.c')

W, H = 12, 12   # the cell: kZhGlyphW/H in port_bottom_ui_zh.h, and the 12px font

HEADER = '''// Generated by tools/ui-font-zh/gen.py from fusion-pixel-font (SIL OFL 1.1), do not edit.
// The 12x12 glyphs port_bottom_ui_zh.c needs, sorted by code point.
#include "port_bottom_ui_zh.h"

static const uint32_t kZhCode[] = {
%s};

// 12 rows of 12 bits each, two bytes a row, bit 15 is the leftmost pixel.
static const uint8_t kZhBits[][kZhGlyphH * 2] = {
%s};

const uint8_t* Port_BottomUiZhGlyph(uint32_t codePoint) {
    int lo = 0;
    int hi = (int)(sizeof(kZhCode) / sizeof(kZhCode[0])) - 1;
    while (lo <= hi) {
        const int mid = (lo + hi) / 2;
        if (kZhCode[mid] == codePoint) return kZhBits[mid];
        if (kZhCode[mid] < codePoint) lo = mid + 1;
        else hi = mid - 1;
    }
    return 0;
}
'''


def parse_bdf(path):
    """{code point: (w, h, xoff, yoff, [rows])}"""
    glyphs, cur, rows, in_bitmap = {}, None, [], False
    with open(path, 'r', encoding='latin-1') as f:
        for line in f:
            line = line.strip()
            if line.startswith('STARTCHAR'):
                cur = {'code': None, 'bbx': None, 'rows': []}
                in_bitmap = False
            elif line.startswith('ENCODING'):
                cur['code'] = int(line.split()[1])
            elif line.startswith('BBX'):
                cur['bbx'] = [int(v) for v in line.split()[1:5]]
            elif line.startswith('BITMAP'):
                in_bitmap = True
            elif line.startswith('ENDCHAR'):
                if cur and cur['code'] is not None and cur['bbx']:
                    glyphs[cur['code']] = (cur['bbx'], cur['rows'])
                cur = None
                in_bitmap = False
            elif in_bitmap and cur is not None:
                cur['rows'].append(line)
    return glyphs


def parse_ttf(path, codes):
    """{code point: 12 rows of bits in the cell}, drawing each character at 12px.

    A pixel font has one bitmap per size, so only the size matters: the glyph is
    drawn at 12px and slid so its own top-left lands on the cell's, whatever the
    font's ascent is."""
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.truetype(path, H)
    out = {}
    for cp in codes:
        ch = chr(cp)
        left, top, _, _ = font.getbbox(ch, anchor='la')
        img = Image.new('L', (W + 16, H + 16), 0)
        ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor='la')
        px = img.load()
        out[cp] = [''.join('1' if px[x, y] > 127 else '0' for x in range(W)) for y in range(H)]
    return out


def used_codepoints():
    """Every non-ASCII character of the catalogue's source.

    The whole file is scanned, comments included: a character in a comment just
    costs 24 bytes and saves a surprise when it moves into a string."""
    with open(CATALOGUE, 'r', encoding='utf-8') as f:
        text = f.read()
    # Below U+2E80 the 5x7 Latin font draws it, so only CJK needs baking.
    return {ord(c) for c in text if ord(c) >= 0x2E80}


def cell(bbx, rows):
    """The glyph's bits in a WxH cell: (w, h, xoff, yoff, rows) -> H strings of W bits."""
    (w, h, xoff, yoff) = bbx
    top = H - (yoff + h)   # the baseline sits on the cell's bottom row
    out = ['0' * W for _ in range(H)]
    for r in range(h):
        hexrow = rows[r] if r < len(rows) else ''
        bits = bin(int(hexrow or '0', 16))[2:].zfill(((w + 7) // 8) * 8) if hexrow else ''
        bits = bits[-(((w + 7) // 8) * 8):] if bits else '0' * w
        for c in range(w):
            if bits[c] == '1':
                y, x = top + r, xoff + c
                if 0 <= y < H and 0 <= x < W:
                    row = list(out[y])
                    row[x] = '1'
                    out[y] = ''.join(row)
    return out


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    wanted = sorted(used_codepoints())
    if not wanted:
        sys.exit('the catalogue has no Chinese in it yet')
    if sys.argv[1].lower().endswith('.ttf'):
        glyphs = parse_ttf(sys.argv[1], wanted)
    else:
        glyphs = {cp: cell(bbx, rows) for cp, (bbx, rows) in parse_bdf(sys.argv[1]).items()}
    missing = [c for c in wanted if c not in glyphs]
    if missing:
        sys.stderr.write('the font has no glyph for: %s\n'
                         % ' '.join('%s(U+%04X)' % (chr(c), c) for c in missing))
        return 1
    code_lines, bit_lines = [], []
    for i, cp in enumerate(wanted):
        bits = glyphs[cp]
        if i % 6 == 0:
            code_lines.append('  ')
        code_lines[-1] += '0x%04X,%s' % (cp, '\n' if i % 6 == 5 else ' ')
        vals = []
        for r in bits:
            v = int(r, 2) << (16 - W)
            vals.append('0x%02X,0x%02X,' % (v >> 8, v & 0xFF))
        bit_lines.append('  ' + ''.join(vals) + '\n')
    if code_lines and not code_lines[-1].endswith('\n'):
        code_lines[-1] += '\n'
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(HEADER % (''.join(code_lines), ''.join(bit_lines)))
    print('%s: %d glyphs, %d bytes of bits' % (os.path.relpath(OUT, ROOT), len(wanted),
                                               len(wanted) * H * 2))
    return 0


if __name__ == '__main__':
    sys.exit(main())
